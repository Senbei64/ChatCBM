"""Generate the test vectors of the 6502 unit tests from the Python integer engine.

    python python/vectors.py --out build/gen      # writes build/gen/vec_<module>.h

Every header holds the inputs of one module of src/ and the outputs that the Python
engine (chatcbm/intengine.py) computes for them: the 6502 code must match them exactly.
Inputs come from a fixed random seed or from real intermediate values of the model.
"""
import argparse
from pathlib import Path

import numpy as np

import export
from chatcbm import intengine

ZERO = intengine.ZERO
MODELS = "models"


def c_array(name, ctype, vals):
    suffix = {"long": "L", "unsigned long": "UL", "unsigned": "u"}.get(ctype, "")
    vals = ["(-32767-1)" if ctype == "int" and int(v) == -32768 else f"{int(v)}{suffix}"
            for v in np.asarray(vals).reshape(-1)]
    body = ",\n".join("    " + ",".join(vals[i:i + 16]) for i in range(0, len(vals), 16))
    return f"static const {ctype} {name}[{len(vals)}] = {{\n{body}\n}};"


def header(module, parts):
    return "\n".join([f"/* generated by python/vectors.py: test vectors of src/{module}.s */", *parts, ""])


# ---- prim.s: ilog16u and pow2_16 -------------------------------------------------
def vec_prim(m, rng):
    t = m.t
    v = np.concatenate([np.arange(1, 1024), rng.integers(1024, 65536, 1000), [65535]])
    e = np.arange(-40, 496)                          # 2^(e/16) < 2^31: no saturation
    return [f"#define ILOG_N {len(v)}", c_array("ilog_in", "unsigned", v),
            c_array("ilog_out", "int", t.ilog16(v)),
            f"#define POW_N {len(e)}", c_array("pow_in", "int", e),
            c_array("pow_out", "long", t.pow2_16(e))]


# ---- real intermediate values of the model -------------------------------------------
def embed(m, tok, pos):
    """Residual stream after the embeddings of one token at one position: int (1, 32)."""
    t, img = m.t, m.img

    def emb(name, row):
        codes = img[name + ".q"][[row]]
        L = img[name + ".k"][[row]][:, None] - intengine.NF4_EXP[codes]
        return t.to_fixed(intengine.NF4_SIGN[codes], L, intengine.NF4_EXP[codes] == ZERO, m.R)
    return emb("wte", tok) + emb("wpe", pos)


def log8_input(m, tok, pos, ln="h0.ln1."):
    """Input of the first linear layer for a token: (sign, e, k) log8 of the LayerNorm output."""
    return m.to_log8(m.layernorm(embed(m, tok, pos), ln))


def random_log8(rng, zeros=4):
    s = rng.integers(0, 2, (1, 32)).astype(bool)
    e = rng.integers(0, 127, (1, 32))
    e[0, rng.choice(32, zeros, replace=False)] = ZERO
    return s, e, np.zeros((1, 1), np.int64)


def kernel_sums(m, wname, x):
    """The products of a linear layer without bias: what src/matmul.s accumulates."""
    sx, ex, _ = x
    sw, ew, _ = m.W[wname]
    prod = np.where((ex[:, :, None] == ZERO) | (ew[None] == ZERO), 0, m.t.prod[ex[:, :, None] + ew[None]])
    return np.where(sx[:, :, None] ^ sw[None], -prod, prod).sum(1)[0]


def image(m):
    return export.build_image(m.img, m.cfg, m.t)


# ---- matmul.s: one 32 x 32 block of packed nf4 weights -----------------------------
def vec_matmul(m, rng):
    b = image(m)
    cases = [("h0.attn.wq", "W_0_wq", log8_input(m, 3, 0)), ("h0.attn.wv", "W_0_wv", log8_input(m, 100, 5)),
             ("h2.ffn.w1", "W_2_w1", log8_input(m, 42, 9, "h2.ln2.")), ("h1.attn.wo", "W_1_wo", random_log8(rng))]
    w, xs, xe, acc = [], [], [], []
    for wname, block, x in cases:
        w += list(b.data[b.offsets[block]:b.offsets[block] + 512])
        xs += list(np.where(x[0][0], 128, 0))
        xe += list(x[1][0])
        acc += list(kernel_sums(m, wname, x))
    return [f"#define CASES {len(cases)}", c_array("weights", "unsigned char", w),
            c_array("prod", "unsigned char", m.img["t.prod"]),
            c_array("nf4log", "unsigned char", export.log8_bytes(np.arange(16))),
            c_array("in_s", "unsigned char", xs), c_array("in_e", "unsigned char", xe),
            c_array("out_acc", "int", acc)]


# ---- log8.s: to_log8 (dynamic scale) and enc_static (static scale per head) --------
def acc_cases(m, rng):
    """(acc, unit) pairs of 32 elements: LayerNorm and linear outputs of the model, random
    values with zeros, all zeros."""
    x = embed(m, 7, 3)
    ln = m.layernorm(x, "h0.ln1.")
    lin = m.linear(m.to_log8(ln), "h0.attn.wq", "h0.attn.bq")
    acc = rng.integers(-32768, 32768, (1, 32))
    acc[0, rng.choice(32, 5, replace=False)] = 0
    rand = (acc, rng.integers(-300, 100, (1, 32)))
    zero = (np.zeros((1, 32), np.int64), np.full((1, 32), -50))
    return [tuple(np.broadcast_to(a, (1, 32)) for a in c) for c in (ln, lin, rand, zero)]


def log8_bytes(neg, e):
    return np.where(e == ZERO, ZERO, e | (neg.astype(np.int64) << 7))


def vec_log8(m, rng):
    cases = acc_cases(m, rng)
    acc, unit, xs, xe, kx, ks, enc = [], [], [], [], [], [], []
    for i, (a, u) in enumerate(cases):
        neg, e, k = intengine.enc_dynamic(*m.t.to_log(a, u))
        acc += list(a[0])
        unit += list(u[0])
        xs += list(np.where(neg[0], 128, 0))          # the sign stays even when e becomes zero
        xe += list(e[0])
        kx.append(int(k[0, 0]))
        K = m.img[f"h{i % m.cfg.n_layer}.Kq"] if i < 2 else rng.integers(-100, 100, 4)
        ks += list(K)
        n, L, z = m.t.to_log(a, u)
        enc += list(log8_bytes(*intengine.enc_static(n, L, z, np.repeat(K, 8)[None]))[0])
    return [f"#define CASES {len(cases)}", c_array("in_acc", "int", acc), c_array("in_unit", "int", unit),
            c_array("out_s", "unsigned char", xs), c_array("out_e", "unsigned char", xe),
            c_array("out_k", "int", kx), c_array("in_K", "int", ks), c_array("out_enc", "unsigned char", enc)]


# ---- linear.s: kernel sums + bias, with saturation -------------------------------
def bias_terms(m, bname, kx, rows):
    """The bias of a linear layer in the unit of the accumulator (intengine.IntModel.linear)."""
    q, s = m.img[bname + ".i"][rows], m.img[bname + ".s"]
    nq, Lq, zq = m.t.to_log(q, 0)
    b = np.where(zq, 0, m.t.pow2_16(Lq + 16 * (m.F - s) - kx))
    return np.where(nq, -b, b)


def vec_linear(m, rng):
    cases = [("h0.attn.wq", "h0.attn.bq", log8_input(m, 3, 0), 0),
             ("h3.ffn.w2", "h3.ffn.b2", log8_input(m, 50, 20, "h3.ln2."), 0),
             ("wte", "b_out", log8_input(m, 9, 4, "lnf."), 64),          # logits 64..95
             ("h1.attn.wk", "h1.attn.bk", random_log8(rng), 0)]
    sums, bias, kw, kx, j0, out, unit = [], [], [], [], [], [], []
    for wname, bname, x, first in cases:
        rows = np.arange(first, first + 32)
        k = int(x[2][0, 0]) - (300 if wname == "h1.attn.wk" else 0)    # far scales saturate
        x = (x[0], x[1], np.full((1, 1), k))
        if wname == "wte":
            sw, ew, kws = m.W["wte"]
            m.W["wte_block"] = (sw[:, rows], ew[:, rows], kws[rows])
            acc = kernel_sums(m, "wte_block", x)
        else:
            acc = kernel_sums(m, wname, x)
            kws = m.img[wname + ".k"]
        sums += list(acc)
        bias += list(export.prep_bias(m.img[bname + ".i"], m.img[bname + ".s"], m.F, m.t)[rows])
        kw += list(kws[rows])
        kx.append(k)
        j0.append(first)
        out += list(intengine.sat16(acc + bias_terms(m, bname, k, rows)))
        unit += list(k + kws[rows] - 16 * m.F)
    return [f"#define CASES {len(cases)}", c_array("in_sum", "int", sums),
            c_array("in_bias", "unsigned", bias), c_array("in_kw", "signed char", kw),
            c_array("in_kx", "int", kx), c_array("in_j0", "int", j0),
            c_array("out_acc", "int", out), c_array("out_unit", "int", unit)]


# ---- layernorm.s ----------------------------------------------------------------------
def ln_params(m, pre, idx):
    """The LayerNorm parameters as stored in the image: gains as log8 bytes, shifted biases."""
    g = log8_bytes(m.img[pre + "g.neg"], m.img[pre + "g.e"])
    b = intengine.shift(m.img[pre + "b.i"], m.F_ln - m.img[pre + "b.s"])
    return g, b, m.img[pre + "g.k"]


def vec_layernorm(m, rng):
    lns = [f"h{i}.ln{j}." for i in range(m.cfg.n_layer) for j in (1, 2)] + ["lnf."]
    cases = [(embed(m, 3, 0), 0), (embed(m, 200, 63), 1),
             (rng.integers(-20000, 20000, (1, 32)), len(lns) - 1),          # final LayerNorm
             (rng.integers(-300, 300, (1, 32)), 5), (np.full((1, 32), 1234), 2)]   # constant: d = 0
    x, g, b, kg, acc, unit = [], [], [], [], [], []
    for xi, idx in cases:
        gi, bi, ki = ln_params(m, lns[idx], idx)
        a, u = m.layernorm(xi, lns[idx])
        x += list(xi[0])
        g += list(gi)
        b += list(bi)
        kg.append(ki)
        acc += list(a[0])
        unit += list(u[0])
    return [f"#define CASES {len(cases)}", c_array("in_x", "int", x), c_array("in_g", "unsigned char", g),
            c_array("in_b", "int", b), c_array("in_kg", "int", kg),
            c_array("out_acc", "int", acc), c_array("out_unit", "int", unit)]


# ---- gelu.s, residual.s, logits.s ---------------------------------------------------
def vec_gelu(m, rng):
    h = log8_input(m, 30, 2, "h1.ln2.")
    cases = [m.linear(h, "h1.ffn.w1", "h1.ffn.b1"),
             (rng.integers(-300, 300, (1, 32)), np.full((1, 32), -16 * m.gf)),      # around the table
             (rng.integers(-32768, 32768, (1, 32)), rng.integers(-200, -60, (1, 32)))]
    acc, unit, out = [], [], []
    for a, u in cases:
        g, _ = m.gelu((a, u))
        acc += list(a[0])
        unit += list(np.broadcast_to(u, (1, 32))[0])
        out += list(g[0])
    return [f"#define CASES {len(cases)}", c_array("table", "int", m.img["t.gelu"]),
            c_array("in_acc", "int", acc), c_array("in_unit", "int", unit), c_array("out_acc", "int", out)]


def vec_residual(m, rng):
    h = log8_input(m, 11, 7)
    lin = m.linear(h, "h0.attn.wo", "h0.attn.bo")
    cases = [(embed(m, 11, 7), lin),
             (rng.integers(-32768, 32768, (1, 32)), (rng.integers(-32768, 32768, (1, 32)), rng.integers(-250, -80, (1, 32)))),
             (np.full((1, 32), 32000), (np.full((1, 32), 20000), np.full((1, 32), -100)))]   # saturation
    x, acc, unit, out = [], [], [], []
    for xi, (a, u) in cases:
        x += list(xi[0])
        acc += list(a[0])
        unit += list(np.broadcast_to(u, (1, 32))[0])
        out += list(intengine.sat16(xi + m.to_resid((a, u)))[0])
    return [f"#define CASES {len(cases)}", c_array("in_x", "int", x), c_array("in_acc", "int", acc),
            c_array("in_unit", "int", unit), c_array("out_x", "int", out)]


def vec_logits(m, rng):
    cases = []
    for tok, pos in ((5, 3), (120, 40)):
        h = log8_input(m, tok, pos, "lnf.")
        acc, _ = m.linear(h, "wte", "b_out")
        cases.append((acc, int(h[2][0, 0])))
    cases.append((rng.integers(-8000, 8000, (1, 256)), cases[0][1]))
    kw = m.img["wte.k"]
    acc, kx, out = [], [], []
    for a, k in cases:
        z = m.t.to_fixed(*m.t.to_log(a, k + kw[None] - 16 * m.F + m.img["Zl"]), 0)
        assert np.abs(z).max() < 32768
        acc += list(a[0])
        kx.append(k)
        out += list(z[0])
    return [f"#define CASES {len(cases)}", c_array("kw", "signed char", kw), c_array("in_acc", "int", acc),
            c_array("in_kx", "int", kx), c_array("out_z", "int", out)]


# ---- attention.s: one head over the KV cache ------------------------------------------
def layer0_qkv(m, tokens):
    """q, k, v of the first layer for a sequence: {name: (neg, e)} of shape (T, 32)."""
    out = {n: ([], []) for n in "qkv"}
    for pos, tok in enumerate(tokens):
        h = log8_input(m, tok, pos)
        for n in "qkv":
            neg, L, zero = m.t.to_log(*m.linear(h, f"h0.attn.w{n}", f"h0.attn.b{n}"))
            neg, e = intengine.enc_static(neg, L, zero, np.repeat(m.img["h0.K" + n], 8)[None])
            out[n][0].append(neg[0])
            out[n][1].append(e[0])
    return {n: (np.array(a), np.array(b)) for n, (a, b) in out.items()}


def head(m, q, k, v, zs):
    """The attention head of intengine.IntModel.step for one query: q (8,), k and v (n, 8)."""
    t, ZA = m.t, m.t.prod_attn
    (qn, qe), (kn, ke), (vn, ve) = q, k, v
    pr = np.where((qe[None] == ZERO) | (ke == ZERO), 0, ZA[qe[None] + ke])
    z = intengine.shift(np.where(qn[None] ^ kn, -pr, pr).sum(-1), zs)
    ez = z.max() - z
    pw = np.where(ez > 16 * m.G, 0, t.pow2_16(16 * m.G - ez))
    ea = ez + t.ilog16(pw.sum()) - 16 * m.G
    ea = np.where(ea > 126, ZERO, ea)
    pr = np.where((ea[:, None] == ZERO) | (ve == ZERO), 0, ZA[ea[:, None] + ve])
    return np.where(vn, -pr, pr).sum(0)


def random_codes(rng, n):
    e = rng.integers(0, 127, (n, 8))
    e[rng.random((n, 8)) < 0.1] = ZERO
    return rng.integers(0, 2, (n, 8)).astype(bool), e


def vec_attention(m, rng):
    from chatcbm.generate import chat_prompt
    from chatcbm.tokenizer import Tokenizer
    tok = Tokenizer.load(Path(MODELS) / "tokenizer.json")
    qkv = layer0_qkv(m, chat_prompt(tok, "tell me a story about the frog"))
    n = len(qkv["q"][0])
    cases = []
    for hd, last in ((1, n - 1), (3, 0), (0, n // 2)):
        sl = slice(8 * hd, 8 * hd + 8)
        cases.append(((qkv["q"][0][last, sl], qkv["q"][1][last, sl]),
                      (qkv["k"][0][:last + 1, sl], qkv["k"][1][:last + 1, sl]),
                      (qkv["v"][0][:last + 1, sl], qkv["v"][1][:last + 1, sl]), int(m.img["h0.Zs"][hd])))
    for count, zs in ((64, 3), (20, -2), (5, 0)):
        qn, qe = random_codes(rng, 1)
        cases.append(((qn[0], qe[0]), random_codes(rng, count), random_codes(rng, count), zs))
    q, k, v, ns, zss, y = [], [], [], [], [], []
    for (qn, qe), (kn, ke), (vn, ve), zs in cases:
        kb, vb = np.zeros((8, 64), np.int64), np.zeros((64, 8), np.int64)
        kb[:, :len(ke)] = log8_bytes(kn, ke).T
        vb[:len(ve)] = log8_bytes(vn, ve)
        q += list(log8_bytes(qn, qe))
        k += list(kb.reshape(-1))
        v += list(vb.reshape(-1))
        ns.append(len(ke))
        zss.append(zs)
        y += list(head(m, (qn, qe), (kn, ke), (vn, ve), zs))
    return [f"#define CASES {len(cases)}", c_array("prod_attn", "unsigned char", m.img["t.prod_attn"]),
            c_array("in_q", "unsigned char", q), c_array("in_k", "unsigned char", k),
            c_array("in_v", "unsigned char", v), c_array("in_n", "unsigned char", ns),
            c_array("in_zs", "signed char", zss), c_array("out_y", "int", y)]


# ---- model.s: whole steps ----------------------------------------------------------------
def vec_model(m, rng):
    from chatcbm.generate import chat_prompt
    from chatcbm.tokenizer import BOT, EOS, PAD, UNK, USER, Tokenizer
    tok = Tokenizer.load(Path(MODELS) / "tokenizer.json")
    prompt = chat_prompt(tok, "tell me a story about the bee and the horse")
    m.reset(1)
    for t in prompt:
        z = m.step(np.array([t]))
    greedy = list(m.generate(prompt, 12, (), (tok.id(PAD), tok.id(UNK), tok.id(BOT))))
    return [f"#define PROMPT_LEN {len(prompt)}", c_array("prompt", "unsigned char", prompt),
            c_array("out_z", "int", z[0]), f"#define GREEDY_LEN {len(greedy)}",
            c_array("out_greedy", "unsigned char", greedy)]


# ---- tokenizer.s ----------------------------------------------------------------------
QUESTIONS = ["what color is the frog?", "  Is the PIG pink?!  ", "hello_world 42, the dog's bone...",
             "hi", "", "\tWHICH is bigger,\n the fox or the owl?", "tell me a story about the bee and the horse",
             "x" * 119, "x" * 121, "a " * 40]


def vec_tokenizer(m, rng):
    from chatcbm.generate import chat_prompt
    from chatcbm.tokenizer import Tokenizer
    tok = Tokenizer.load(Path(MODELS) / "tokenizer.json")
    text, ids, lens = [], [], []
    for q in QUESTIONS:
        p = chat_prompt(tok, q)
        normalized = len(" " + " ".join(q.split()))
        fits = normalized <= 120 and len(p) <= m.cfg.context - 1
        text += list(q.encode("ascii")) + [0]
        ids += (p if fits else []) + [0] * (64 - (len(p) if fits else 0))
        lens.append(len(p) if fits else 0)          # 0 = too long
    return [f"#define CASES {len(QUESTIONS)}", c_array("in_text", "char", text),
            c_array("out_ids", "unsigned char", ids), c_array("out_len", "unsigned char", lens)]


# ---- sampler.s ----------------------------------------------------------------------------
DRAWS = 6


def vec_sampler(m, rng):
    from chatcbm.generate import chat_prompt
    from chatcbm.tokenizer import BOT, PAD, UNK, Tokenizer
    tok = Tokenizer.load(Path(MODELS) / "tokenizer.json")
    banned = [tok.id(PAD), tok.id(UNK), tok.id(BOT)]
    zs = []
    for q in ("tell me a story", "what color is the frog?", "hi"):
        m.reset(1)
        for t in chat_prompt(tok, q):
            z = m.step(np.array([t]))
        zs.append(z[0])
    zs.append(rng.integers(-3000, 3000, 256))                    # flat: many tokens in the top-p
    zs.append(np.where(np.arange(256) == 77, 2000, -2000))       # one clear winner
    seeds = [2026, 1, 123456789, 42, 7]
    z_in, seed_in, best, draws = [], [], [], []
    for z, seed in zip(zs, seeds):
        zb = z.copy()
        zb[banned] = intengine.NEG_INF
        sampler = intengine.IntSampler(0.6, 0.9, seed)
        z_in += list(z)
        seed_in.append(seed)
        best.append(int(np.argmax(zb)))
        draws += [sampler(zb) for _ in range(DRAWS)]
    return [f"#define CASES {len(zs)}", f"#define DRAWS {DRAWS}", c_array("in_z", "int", z_in),
            c_array("in_seed", "unsigned long", seed_in), c_array("out_argmax", "unsigned char", best),
            c_array("out_draws", "unsigned char", draws)]


GENERATORS = {"prim": vec_prim, "tokenizer": vec_tokenizer, "sampler": vec_sampler, "matmul": vec_matmul, "log8": vec_log8, "linear": vec_linear,
              "layernorm": vec_layernorm, "gelu": vec_gelu, "residual": vec_residual, "logits": vec_logits,
              "attention": vec_attention, "model": vec_model}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--models", default="models")
    ap.add_argument("--out", default="build/gen")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    global MODELS
    MODELS = args.models
    m = intengine.IntModel(intengine.load(Path(args.models) / "model_int.npz"))
    for name, gen in GENERATORS.items():
        text = header(name, gen(m, np.random.default_rng(2026)))
        (out / f"vec_{name}.h").write_text(text, encoding="utf-8", newline="\n")
    print(f"{out}: test vectors for {', '.join(GENERATORS)}")


if __name__ == "__main__":
    main()

