"""Generate the test vectors of the 6502 unit tests from the Python integer engine.

    python python/vectors.py --out build/gen      # writes build/gen/vec_<module>.h

Every header holds the inputs of one module of src/ and the outputs that the Python
engine (chatcbm/intengine.py) computes for them: the 6502 code must match them exactly.
Inputs come from a fixed random seed or from real intermediate values of the model.
"""
import argparse
from pathlib import Path

import numpy as np

from chatcbm import intengine


def c_array(name, ctype, vals):
    suffix = {"long": "L", "unsigned long": "UL", "unsigned": "u"}.get(ctype, "")
    vals = [f"{int(v)}{suffix}" for v in np.asarray(vals).reshape(-1)]
    body = ",\n".join("    " + ",".join(vals[i:i + 16]) for i in range(0, len(vals), 16))
    return f"static const {ctype} {name}[{len(vals)}] = {{\n{body}\n}};"


def header(module, parts):
    return "\n".join([f"/* generated by python/vectors.py: test vectors of src/{module}.s */", *parts, ""])


# ---- prim.s: ilog16u and pow2_16 -------------------------------------------------
def vec_prim(m, rng):
    t = m.t
    v = np.concatenate([np.arange(1, 1024), rng.integers(1024, 65536, 1000), [65535]])
    e = np.arange(-40, 496)                          # 2^(e/16) < 2^31: no saturation
    return [f"#define ILOG_N {len(v)}", c_array("ilog_in", "unsigned", v),
            c_array("ilog_out", "int", t.ilog16(v)),
            f"#define POW_N {len(e)}", c_array("pow_in", "int", e),
            c_array("pow_out", "long", t.pow2_16(e))]


GENERATORS = {"prim": vec_prim}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--models", default="models")
    ap.add_argument("--out", default="build/gen")
    args = ap.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    m = intengine.IntModel(intengine.load(Path(args.models) / "model_int.npz"))
    for name, gen in GENERATORS.items():
        text = header(name, gen(m, np.random.default_rng(2026)))
        (out / f"vec_{name}.h").write_text(text, encoding="utf-8", newline="\n")
    print(f"{out}: test vectors for {', '.join(GENERATORS)}")


if __name__ == "__main__":
    main()

